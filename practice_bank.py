import random

def generate_practice(spec):
 rng=random.Random(random.SystemRandom().getrandbits(64));n=rng.randint(3,12)
 items={
  'backend':[
   (f'API ограничивает клиента до {n} запросов в минуту. Клиент уже отправил {n} запросов. Какой статус подходит для следующего запроса?', '429', '200', '201', '404'),
   ('Что делать с секретным API-ключом приложения?', 'Хранить в серверном окружении, исключить из Git', 'Добавить в публичный JavaScript', 'Разместить в README', 'Отправлять каждому пользователю'),
   ('Зачем задать timeout для обращения к внешнему сервису?', 'Ограничить время ожидания и обработать недоступность', 'Заменить авторизацию', 'Гарантировать успешный ответ', 'Отключить проверку ответа')],
  'frontend':[
   (f'На странице {n} изображений ниже первого экрана. Как уменьшить начальную сетевую нагрузку?', 'Использовать отложенную загрузку этих изображений', 'Загружать каждое изображение трижды', 'Перевести изображения в текст', 'Убрать текстовые подписи'),
   ('Форма получает данные пользователя. Как подписать поле email?', 'Видимой подписью label, связанной с полем', 'Только случайным номером', 'Только цветом рамки', 'Скрыть название поля'),
   ('Ссылка должна открывать страницу документации. Какой элемент выбрать?', 'a с адресом href', 'div без обработчика', 'span с цветом ссылки', 'input type=password')],
  'data':[
   (f'Набор содержит {n} строк, из них одна полностью дублирует другую. Сколько строк останется после удаления полного дубля?', str(n-1),str(n),str(n+1),'0'),
   ('Как описать неизвестную дату события в наборе данных?', 'Использовать пропуск и документировать его смысл', 'Всегда подставлять сегодняшнюю дату', 'Всегда подставлять 1970 год', 'Подставлять случайную дату'),
   ('Два источника используют рубли и тысячи рублей. Что сделать перед суммированием?', 'Привести значения к единой единице', 'Сложить значения без изменений', 'Удалить все большие значения', 'Отсортировать имена файлов')],
 }[spec]
 qs=[]
 for i,(prompt,*choices) in enumerate(items):
  indices=list(range(4));rng.shuffle(indices)
  qs.append({'id':f'practice-{i}','prompt':prompt,'options':[choices[j] for j in indices],'answer':indices.index(0)})
 return {'questions':qs}
